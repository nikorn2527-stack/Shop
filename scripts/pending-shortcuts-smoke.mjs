import puppeteer from 'puppeteer';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const cfg = JSON.parse(fs.readFileSync(path.join(os.tmpdir(), 'shop-ui-test-config.json'), 'utf8'));
const browser = await puppeteer.launch({headless: true, pipe: true, args: ['--no-sandbox']});
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewport({width: 1366, height: 768});
  await page.goto(process.env.AUDIT_BASE_URL ?? 'http://localhost:4173', {waitUntil: 'networkidle2'});
  await page.type('[name=username]', cfg.username);
  await page.type('[name=password]', cfg.password);
  await page.click('.login-submit');
  await page.waitForSelector('.app-shell');
  const clickText = async text => page.evaluate(text => {
    const b = [...document.querySelectorAll('button')].find(b => b.getClientRects().length && b.innerText.includes(text));
    if (!b) throw new Error('Missing button: ' + text);
    b.click();
  }, text);
  await clickText('POS');
  await page.waitForSelector('.rail-limit');
  assert.equal(await page.$('.rail-manage'), null);
  await page.click('.rail-limit');
  await page.waitForSelector('#pos-limit-member');
  await page.type('#pos-limit-member', '1');
  await page.waitForSelector('.member-option');
  await page.click('.member-option:not(:first-child)');
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.innerText.includes('ยืนยันใช้กับ')));
  await clickText('ยืนยัน');
  await page.waitForSelector('.limit-dialog');
  await page.type('.limit-dialog input[type=number]', '0');
  await clickText('ต่อไป');
  await page.waitForFunction(() => document.querySelector('.limit-dialog .notice-bar.error'));
  await page.$eval('.limit-dialog input[type=number]', e => {e.select();});
  await page.type('.limit-dialog input[type=number]', '1');
  await clickText('ต่อไป');
  await page.waitForFunction(() => document.querySelector('.limit-dialog')?.innerText.includes('ส่งคำขอ'));
  await page.screenshot({path: path.join(cfg.dir, 'pending-limit-confirm.png')});
  await page.click('.limit-dialog .modal-heading button');
  await page.keyboard.press('F7');
  await page.waitForSelector('.quick-manage-modal');
  await page.keyboard.press('Escape');
  await page.click('.rail-exit');
  await clickText('ตั้งค่า');
  await page.waitForSelector('.settings-content');
  await page.evaluate(() => [...document.querySelectorAll('.settings-nav button')].find(b => /แบรนด์/.test(b.innerText))?.click());
  await page.waitForSelector('input[placeholder="ชื่อร้านค้า"]');
  const input = await page.$('input[placeholder="ชื่อร้านค้า"]');
  assert.ok(input);
  await input.focus();
  await page.keyboard.press('End');
  await page.keyboard.type('Audit');
  await page.waitForSelector('.settings-save-bar');
   const saveCard = await page.$eval('.settings-save-bar', e => {
     const r = e.getBoundingClientRect();
     return {position: getComputedStyle(e).position, bottom: r.bottom, top: r.top, viewport: innerHeight};
   });
   assert.equal(saveCard.position, 'fixed');
   assert.ok(saveCard.top >= 0 && saveCard.bottom <= saveCard.viewport, 'Unsaved card must appear without scrolling');
   await new Promise(resolve => setTimeout(resolve, 3500));
   assert.ok(await page.$('.settings-save-bar'), 'Unsaved card must not disappear automatically');
  assert.ok(await page.$eval('.settings-save-bar', e => e.getBoundingClientRect().width <= 521));
  await page.screenshot({path: path.join(cfg.dir, 'pending-settings-save.png')});
  await clickText('ย้อนการแก้ไข');
  await page.waitForFunction(() => !document.querySelector('.settings-save-bar'));
  assert.deepEqual(errors, []);
  console.log('PASS sidebar duplicate removed, member picker, shared limit validation/confirmation, F7, compact persistent save card and discard; no live request submitted');
} finally {await browser.close();}