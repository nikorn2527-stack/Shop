-- PostgreSQL initial schema for isolated migration rehearsals.
-- NOT a live Shop provider switch. Run through the guarded export command.
-- All foreign keys are deferrable so an import is checked as one transaction.
CREATE SCHEMA shop;
SET LOCAL search_path = shop, pg_catalog;
SET LOCAL TIME ZONE 'Asia/Bangkok';
SET LOCAL standard_conforming_strings = on;

CREATE TABLE shop."app_sessions" (
  "id" text PRIMARY KEY,
  "user_id" bigint NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL,
  "last_seen_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE shop."app_users" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "username" text NOT NULL UNIQUE,
  "password_hash" text NOT NULL,
  "display_name" text NOT NULL,
  "role" text NOT NULL DEFAULT 'staff',
  "active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL,
  "failed_attempts" bigint NOT NULL DEFAULT 0,
  "must_change_password" boolean NOT NULL DEFAULT false,
  "locked_until" timestamptz
);

CREATE TABLE shop."audit_logs" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "action" text NOT NULL,
  "actor" text NOT NULL,
  "actor_role" text,
  "detail" text,
  "tone" text NOT NULL DEFAULT 'blue',
  "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE shop."card_assignments" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "card_number" text NOT NULL,
  "member_number" text NOT NULL,
