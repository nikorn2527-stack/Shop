CREATE TABLE shop."sale_lot_allocations" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sale_item_id" bigint NOT NULL,
  "lot_id" bigint NOT NULL,
  "qty" bigint NOT NULL,
  "cost_satang" bigint NOT NULL,
  "valuation_source" text NOT NULL,
