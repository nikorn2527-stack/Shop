CREATE TABLE shop."refunds" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sale_id" bigint NOT NULL,
  "amount" numeric(20,2) NOT NULL,
  "reason" text NOT NULL,
