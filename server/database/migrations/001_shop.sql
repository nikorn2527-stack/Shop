CREATE TABLE shop."sale_items" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sale_id" bigint NOT NULL,
  "product_id" bigint,
  "name" text NOT NULL,
  "qty" bigint NOT NULL,
  "price" numeric(24,10) NOT NULL,
